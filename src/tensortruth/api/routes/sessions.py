router = APIRouter()


def _session_to_response(session_id: str, session: dict) -> SessionResponse:
    """Convert internal session dict to response schema."""
    return SessionResponse(
        session_id=session_id,
        title=session.get("title", "New Session"),
        created_at=session.get("created_at", ""),
        modules=session.get("modules"),
        module_mode=session.get("module_mode", "manual"),
        params=session.get("params", {}),
        message_count=len(session.get("messages", [])),
        project_id=session.get("project_id"),
    )


@router.get("", response_model=SessionListResponse)
async def list_sessions(session_service: SessionServiceDep) -> SessionListResponse:
    """List all chat sessions."""
    data = session_service.load()
    sessions = [_session_to_response(sid, sess) for sid, sess in data.sessions.items()]
    # Sort by created_at descending (newest first)
    sessions.sort(key=lambda s: s.created_at, reverse=True)
    return SessionListResponse(sessions=sessions, current_id=data.current_id)


@router.post("", response_model=SessionResponse, status_code=201)
async def create_session(
    body: SessionCreate,
    session_service: SessionServiceDep,
    config_service: ConfigServiceDep,
) -> SessionResponse:
    """Create a new chat session."""
    data = session_service.load()
    new_id, new_data = session_service.create(
        modules=body.modules,
        module_mode=body.module_mode,
        params=body.params,
        data=data,
        config_service=config_service,
        title=body.title,
    )
    session_service.save(new_data)
    session = new_data.sessions[new_id]
    return _session_to_response(new_id, session)


@router.post("/title-preview", response_model=TitlePreviewResponse)
async def preview_title(
    body: TitlePreviewRequest, config_service: ConfigServiceDep
) -> TitlePreviewResponse:
    """Title a session from a prompt the user is still drafting.

    Called by the composer after a few words so the new chat is already
    labelled when it is created, instead of showing "New Session" until the
    first answer completes.
    """
    from tensortruth.app_utils.title_generation import (
        build_title_source,
        generate_smart_title_async,
    )

    text = build_title_source(body.prompt)
    if not text:
        raise HTTPException(status_code=400, detail="Empty prompt")

    # The welcome screen often does not know the model yet (its model list is
    # only queried when the picker opens), which used to fall back to a raw
    # 60-char truncation. Fall back to the configured default instead.
    config = config_service.load()
    model_name = body.model or config.llm.default_model
    context_window = body.context_window or config.llm.default_context_window

    # The title is generated by the model the composer is about to use, and
    # only by it — no provider guessing here.
    title = await generate_smart_title_async(
        text,
        model_name,
        context_window,
        provider_id=body.provider_id,
    )
    return TitlePreviewResponse(title=title)


@router.get("/{session_id}", response_model=SessionResponse)
async def get_session(
    session_id: str, session_service: SessionServiceDep
) -> SessionResponse:
    """Get a session by ID."""
    data = session_service.load()
    session = session_service.get_session(session_id, data)
    if session is None:
        raise HTTPException(status_code=404, detail="Session not found")
    return _session_to_response(session_id, session)


@router.patch("/{session_id}", response_model=SessionResponse)
async def update_session(
    session_id: str, body: SessionUpdate, session_service: SessionServiceDep
) -> SessionResponse:
    """Update a session (title, modules, params)."""
    data = session_service.load()
    session = session_service.get_session(session_id, data)
    if session is None:
        raise HTTPException(status_code=404, detail="Session not found")

    # Update title if provided
    if body.title is not None:
        data = session_service.update_title(session_id, body.title, data)

    # Update modules or params if provided
    if (
        body.modules is not None
        or body.params is not None
        or body.module_mode is not None
    ):
        from tensortruth.services import SessionData

        new_sessions = dict(data.sessions)
        new_sessions[session_id] = dict(new_sessions[session_id])

        if body.modules is not None:
            new_sessions[session_id]["modules"] = body.modules

        if body.module_mode is not None:
            new_sessions[session_id]["module_mode"] = body.module_mode

        if body.params is not None:
            new_sessions[session_id]["params"] = body.params

        data = SessionData(current_id=data.current_id, sessions=new_sessions)

    session_service.save(data)
    return _session_to_response(session_id, data.sessions[session_id])


@router.delete("/{session_id}", status_code=204)
async def delete_session(
    session_id: str,
    session_service: SessionServiceDep,
    project_service: ProjectServiceDep,
) -> None:
    """Delete a session."""
    data = session_service.load()
    if session_id not in data.sessions:
        raise HTTPException(status_code=404, detail="Session not found")

    # Remove session from its project if it belongs to one
    session = data.sessions[session_id]
    project_id = session.get("project_id")
    if project_id:
        project_data = project_service.load()
        project_data = project_service.remove_session(
            project_id, session_id, project_data
        )
        project_service.save(project_data)

    session_dir = get_session_dir(session_id)
    new_data = session_service.delete(session_id, data, session_dir=session_dir)
    session_service.save(new_data)

    # Drop the persisted context snapshot for the deleted session.
    from tensortruth.services.context_accounting import clear_snapshot

    clear_snapshot(session_id)

    # Drop this session's in-memory retrieval set so its module refcounts are
    # returned and the engine can be collected.
    from tensortruth.api.deps import get_rag_service

    get_rag_service().release(session_id)


@router.delete("/{session_id}/messages/{message_index}", status_code=204)
async def delete_message(
    session_id: str, message_index: int, session_service: SessionServiceDep
) -> None:
    """Delete a single message by index."""
    data = session_service.load()
    if session_id not in data.sessions:
        raise HTTPException(status_code=404, detail="Session not found")

    try:
        new_data = session_service.delete_message(session_id, message_index, data)
    except ValueError as e:
        raise HTTPException(status_code=400, detail=str(e))

    session_service.save(new_data)


@router.get("/{session_id}/messages", response_model=MessagesResponse)
async def get_messages(
    session_id: str, session_service: SessionServiceDep
) -> MessagesResponse:
    """Get all messages for a session."""
    data = session_service.load()
    if session_id not in data.sessions:
        raise HTTPException(status_code=404, detail="Session not found")

    messages = session_service.get_messages(session_id, data)
    return MessagesResponse(
        messages=[
            MessageResponse(
                role=msg.get("role", "user"),
                content=msg.get("content", ""),
                sources=msg.get("sources"),
                thinking=msg.get("thinking"),
                narration_segments=msg.get("narration_segments"),
                metrics=msg.get("metrics"),
                tool_steps=msg.get("tool_steps"),
                confidence_level=msg.get("confidence_level"),
                images=msg.get("images"),
            )
            for msg in messages
        ]
    )


@router.get("/{session_id}/images/{image_id}")
async def get_image(session_id: str, image_id: str) -> FileResponse:
    """Serve a stored chat image."""
    image_service = ImageService()
    image_path = image_service.get_image_path(session_id, image_id)
    if image_path is None:
        raise HTTPException(status_code=404, detail="Image not found")
    media_type = image_service.get_mimetype(image_path)
    return FileResponse(path=str(image_path), media_type=media_type)


@router.get("/{session_id}/stats", response_model=SessionStatsResponse)
async def get_session_stats(
    session_id: str,
    session_service: SessionServiceDep,
    config_service: ConfigServiceDep,
    chat_history_service: ChatHistoryServiceDep,
) -> SessionStatsResponse:
    """Get chat statistics for a specific session.

    Returns:
    - history_messages: Total number of messages stored in the session
    - history_chars: Total characters across all messages (after cleaning if enabled)
    - compiled_history_*: Stats for the history actually sent to LLM per config
    - model_name: Name of the LLM model configured for the session
    - context_length: Session's configured context window size
    """
    data = session_service.load()
    session = session_service.get_session(session_id, data)
    if session is None:
        raise HTTPException(status_code=404, detail="Session not found")

    messages = session.get("messages", [])
    params = session.get("params", {})
    model_name = params.get("model")
    config = config_service.load()

    # Calculate total history stats (apply cleaning if enabled)
    history_messages = len(messages)

    if config.history_cleaning.enabled:
        cleaner_config = HistoryCleanerConfig(
            enabled=True,
            remove_emojis=config.history_cleaning.remove_emojis,
            remove_filler_phrases=config.history_cleaning.remove_filler_phrases,
            normalize_whitespace=config.history_cleaning.normalize_whitespace,
            collapse_newlines=config.history_cleaning.collapse_newlines,
            filler_phrases=config.history_cleaning.filler_phrases,
        )
        history_chars = sum(
            len(clean_history_content(m.get("content", ""), cleaner_config) or "")
            for m in messages
        )
    else:
        history_chars = sum(len(m.get("content", "")) for m in messages)

    history_tokens_estimate = history_chars // 4  # Rough approximation

    # Calculate compiled history stats (what's actually sent to LLM)
    # Session params can override max_history_turns
    max_turns = params.get("max_history_turns")
    compiled_history = chat_history_service.build_history(
        messages,
        max_turns=max_turns,
        apply_cleaning=config.history_cleaning.enabled,
    )

    compiled_history_messages = len(compiled_history.messages)
    compiled_history_chars = sum(len(m.content) for m in compiled_history.messages)
    compiled_history_tokens_estimate = compiled_history_chars // 4

    # Get the effective max_history_turns limit
    effective_max_turns = (
        max_turns if max_turns is not None else config.conversation.max_history_turns
    )

    # Get configured context window from session params
    context_length = params.get("context_window", 0)

    return SessionStatsResponse(
        history_messages=history_messages,
        history_chars=history_chars,
        history_tokens_estimate=history_tokens_estimate,
        compiled_history_messages=compiled_history_messages,
        compiled_history_chars=compiled_history_chars,
        compiled_history_tokens_estimate=compiled_history_tokens_estimate,
        max_history_turns=effective_max_turns,
        model_name=model_name,
        context_length=context_length,
    )


@router.post("/{session_id}/messages", response_model=MessageResponse, status_code=201)
async def add_message(
    session_id: str, body: MessageCreate, session_service: SessionServiceDep
) -> MessageResponse:
    """Add a message to a session."""
    data = session_service.load()
    if session_id not in data.sessions:
        raise HTTPException(status_code=404, detail="Session not found")

    message = {"role": body.role, "content": body.content}
    new_data = session_service.add_message(session_id, message, data)
    session_service.save(new_data)

    return MessageResponse(role=body.role, content=body.content)


